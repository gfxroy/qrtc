// Ensure clean 1024 word array length
const WORDS = WORDLIST.slice(0, 1024);

export function generateSafetyCode(fp1: string, fp2: string): string {
  // Normalize fingerprints (remove colons, spaces, uppercase)
  const norm1 = fp1.replace(/[^a-fA-F0-9]/g, "").toLowerCase();
  const norm2 = fp2.replace(/[^a-fA-F0-9]/g, "").toLowerCase();

  // Sort lexicographically to guarantee identical order on both sides
  const sorted = [norm1, norm2].sort();
  const input = `${sorted[0]}:${sorted[1]}`;

  // SHA-256 hash input
  const hash = IncrementalSha256.hash(input);

  // Take 4 groups of 2 hex bytes (16-bit values modulo 1024)
  const words: string[] = [];
  for (let i = 0; i < 4; i++) {
    const hexSlice = hash.substring(i * 4, i * 4 + 4);
    const value = parseInt(hexSlice, 16);
    const index = value % WORDS.length;
    words.push(WORDS[index]);
  }

  return words.join(" ");
}
